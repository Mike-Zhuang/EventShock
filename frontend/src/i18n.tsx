export function translateValidation(code: string, fallback: string | undefined, t: I18nContextValue['t']): string {
  const keys: Record<string, TranslationKey> = {
    EVENT_PACK_NOT_FOUND: 'validation.eventPackNotFound',
    EVENT_PACK_NOT_FROZEN: 'validation.eventPackNotFrozen',
    INTERVENTION_HAS_NO_DIFF: 'validation.noDiff',
    SMALL_SEED_COUNT: 'validation.smallSeeds',
  };
  const key = keys[code];
  return key ? t(key) : fallback ?? code;
}

export function translateAgentType(agentType: string, t: I18nContextValue['t']): string {
  const normalized = agentType.replace(/[A-Z]/g, (letter) => `_${letter}`).replace(/^_/, '').toUpperCase();
  const keys: Record<string, TranslationKey> = {
    VALUE: 'agent.value',
    VALUE_INVESTOR: 'agent.value',
    TREND: 'agent.trend',
    TREND_FOLLOWER: 'agent.trend',
    PASSIVE: 'agent.passive',
    PASSIVE_FUND: 'agent.passive',
    MARKET_MAKER: 'agent.marketMaker',
    RETAIL: 'agent.retail',
    INFLUENCER: 'agent.influencer',
    NOISE: 'agent.noise',
    MOMENTUM: 'agent.momentum',
    MEAN_REVERSION: 'agent.meanReversion',
    STOP_LOSS: 'agent.stopLoss',
  };
  const key = keys[normalized];
  return key ? t(key) : agentType.replaceAll('_', ' ').toLowerCase();
}

export function translateLogLevel(level: string, t: I18nContextValue['t']): string {
  const keys: Record<string, TranslationKey> = {
    INFO: 'log.info',
    WARNING: 'log.warning',
    ERROR: 'log.error',
  };
  const key = keys[level.toUpperCase()];
  return key ? t(key) : level;
}
